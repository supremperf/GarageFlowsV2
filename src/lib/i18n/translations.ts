// ── Fusion base + clés UI (ui.ts) dans chaque langue ─────────────────────────
export const translations: Record<LangCode, T> = LANGUAGES.reduce((acc, l) => {
  const code = l.code as LangCode
  const merged = { ...base[code] } as T
  for (const k of Object.keys(UI) as UIKey[]) {
    (merged as Record<string, string>)[k] = UI[k][code] ?? UI[k].en ?? UI[k].fr
  }
  acc[code] = merged
  return acc
}, {} as Record<LangCode, T>)
