'use strict'
/** Read-only TS diagnostics. Historical sources are overlaid in memory, never checked out.
 * Same installed dependencies/current environment for all versions; not historical CI replay.
 * No exclusions, fake Prisma types, suppression, emission or source/error text in report.
 */
const ts = require('typescript')
const fs = require('node:fs')
const path = require('node:path')
const { execFileSync } = require('node:child_process')
const root = path.resolve(__dirname, '..')
const args = process.argv.slice(2)
const typed = args[0] === '--official-types'
const typesRoot = typed ? path.resolve(args[1] || '') : null
const versions = typed ? args.slice(2) : args
if (typed && (!typesRoot || typesRoot.startsWith(root + path.sep))) throw new Error('Diagnostic types must be outside repository')
if (!versions.length) versions.push('working', 'bd05cd521917cc059fc21780d1b562c020534942', '4f19f77891debc6009a1c241d2689f2a42bca0e8')
const git = args => execFileSync('git', args, { cwd: root, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 })
function diagnose(version) {
  if (version !== 'working' && !/^[a-f0-9]{40}$/.test(version)) throw new Error('Full SHA required')
  const tracked = version === 'working' ? null : new Set(git(['ls-tree', '-r', '--name-only', version]).trim().split('\n'))
  const cache = new Map()
  const rel = file => path.relative(root, path.resolve(file)).split(path.sep).join('/')
  const overlay = file => tracked && !rel(file).startsWith('node_modules/') && !rel(file).startsWith('../') && rel(file) !== 'next-env.d.ts'
  const read = file => {
    if (!overlay(file)) return ts.sys.readFile(file)
    const p = rel(file)
    if (!tracked.has(p)) return undefined
    if (!cache.has(p)) cache.set(p, git(['show', `${version}:${p}`]))
    return cache.get(p)
  }
  const configFile = path.join(root, 'tsconfig.json')
  const config = ts.parseConfigFileTextToJson(configFile, read(configFile))
  if (config.error) throw new Error('Invalid TS config')
  const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root)
  if (parsed.errors.length) throw new Error('Invalid TS options')
  // Baseline source inventory removes only files which did not exist at that SHA.
  const files = tracked ? [...tracked].filter(p => /\.tsx?$/.test(p) && !p.startsWith('node_modules/')).map(p => path.join(root, p)) : parsed.fileNames
  if (tracked && fs.existsSync(path.join(root, 'next-env.d.ts'))) files.push(path.join(root, 'next-env.d.ts'))
  const options = { ...parsed.options, incremental: false, noEmit: true }
  const host = ts.createCompilerHost(options)
  host.readFile = read
  host.fileExists = file => overlay(file) ? tracked.has(rel(file)) : ts.sys.fileExists(file)
  host.getSourceFile = (file, language) => {
    const text = read(file)
    return text === undefined ? undefined : ts.createSourceFile(file, text, language)
  }
  if (typed) {
    // Genuine declaration files generated by the locked official generator from our schemas.
    // Module mapping is DIAGNOSTIC ONLY: never written to tsconfig or runtime imports.
    host.resolveModuleNames = (names, containingFile) => names.map(name => {
      const profile = name === '@prisma/client' ? 'desktop' : /(?:@\/|\.\.\/src\/)generated\/server-client$/.test(name) ? 'server' : null
      if (profile) return { resolvedFileName: path.join(typesRoot, profile, 'index.d.ts'), extension: ts.Extension.Dts, isExternalLibraryImport: false }
      return ts.resolveModuleName(name, containingFile, options, host).resolvedModule
    })
  }
  const program = ts.createProgram(files, options, host)
  const diagnostics = ts.getPreEmitDiagnostics(program).map(d => {
    const pos = d.file && d.start !== undefined ? d.file.getLineAndCharacterOfPosition(d.start) : null
    return { file: d.file ? rel(d.file.fileName) : null, line: pos ? pos.line + 1 : null, character: pos ? pos.character + 1 : null, code: `TS${d.code}`,
      rootCause: [2305, 2307].includes(d.code) && (ts.flattenDiagnosticMessageText(d.messageText, ' ').includes('prisma') || ts.flattenDiagnosticMessageText(d.messageText, ' ').includes('server-client')) ? 'generated_client_missing_direct' : 'requires_generated_types_to_disambiguate' }
  })
  const codes = {}, causes = {}
  for (const d of diagnostics) { codes[d.code] = (codes[d.code] || 0) + 1; causes[d.rootCause] = (causes[d.rootCause] || 0) + 1 }
  return { version, total: diagnostics.length, codes, causes, diagnostics }
}
const reports = versions.map(diagnose)
console.log(JSON.stringify({ at: new Date().toISOString(), typescript: ts.version, head: git(['rev-parse', 'HEAD']).trim(),
  diagnosticOfficialTypes: typed, nativeRuntimeValidated: false, limits: 'Read-only attribution under CURRENT dependencies. Optional official declaration mapping is diagnostic only, no native runtime or standard tsc success. Compare unmodified and mapped runs to identify cascades. No historical dependency replay.', reports }, null, 2))
if (reports.some(r => r.total)) process.exitCode = 2
