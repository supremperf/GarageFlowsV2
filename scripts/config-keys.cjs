'use strict'
// Public-only creation receipt: supports interrupted first installs, never stores a secret.
const fs = require('node:fs')
const path = require('node:path')
const core = require('./config-core.cjs')
const { publicFingerprint } = require('./config-services.cjs')

const stateFile = root => path.join(root, 'GarageFlow-configuration/generated-keys.json')
function readState(root) {
  const file = stateFile(root)
  if (!fs.existsSync(file)) return null
  let state
  try { state = JSON.parse(fs.readFileSync(file, 'utf8')) } catch { throw new Error('Reçu de création des clés illisible ; aucune nouvelle clé de remplacement générée.') }
  if (!state || state.schemaVersion !== 1 || typeof state.autoGenerated !== 'boolean' ||
      !/^[0-9a-f]{64}$/.test(state.licensePublicFingerprint) || typeof state.publisherInitialized !== 'boolean') {
    throw new Error('Reçu de création des clés invalide ; aucune nouvelle clé de remplacement générée.')
  }
  return state
}
function recordCreation(root, publicPem, autoGenerated) {
  const state = { schemaVersion: 1, autoGenerated, licensePublicFingerprint: publicFingerprint(publicPem), publisherInitialized: false }
  core.writePrivate(stateFile(root), JSON.stringify(state, null, 2) + '\n', { exclusive: true })
  return state
}
function matchesIssuer(state, privatePem) {
  return state && publicFingerprint(privatePem) === state.licensePublicFingerprint
}
function mayCreatePublisher(root, privatePem, emptyDatabase, hasPublisherConfig) {
  const state = readState(root)
  return !!(emptyDatabase && !hasPublisherConfig && state?.autoGenerated && !state.publisherInitialized && matchesIssuer(state, privatePem))
}
function recordPublisher(root, privatePem) {
  const state = readState(root)
  if (!state) return
  if (!matchesIssuer(state, privatePem)) throw new Error('Reçu de clés : autorité différente, état de publication laissé intact.')
  core.writePrivate(stateFile(root), JSON.stringify({ ...state, publisherInitialized: true }, null, 2) + '\n')
}
module.exports = { stateFile, readState, recordCreation, matchesIssuer, mayCreatePublisher, recordPublisher }
